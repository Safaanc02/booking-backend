-- Cohérence des coordonnées d'un salon
------------------------------------------------------------------------------
-- Une latitude sans longitude ne situe rien : la moitié d'un point est une
-- donnée fausse qui se propage silencieusement dans un calcul de distance.
ALTER TABLE salon
    ADD CONSTRAINT chk_salon_latitude  CHECK (latitude  IS NULL OR latitude  BETWEEN -90  AND 90),
    ADD CONSTRAINT chk_salon_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    ADD CONSTRAINT chk_salon_point_complet CHECK ((latitude IS NULL) = (longitude IS NULL));

------------------------------------------------------------------------------
-- Rattrapage des salons déjà enregistrés
------------------------------------------------------------------------------
-- Le quartier d'abord, la ville ensuite : un salon du Maarif est placé au
-- Maarif, pas au centre de Casablanca. WHERE latitude IS NULL : ce rattrapage
-- ne remplace jamais une coordonnée relevée à la main.
UPDATE salon s
   SET latitude = r.latitude, longitude = r.longitude
  FROM repere_geo r
 WHERE s.latitude IS NULL
   AND r.quartier IS NOT NULL
   AND normaliser_libelle(s.ville)    = normaliser_libelle(r.ville)
   AND normaliser_libelle(s.quartier) = normaliser_libelle(r.quartier);

UPDATE salon s
   SET latitude = r.latitude, longitude = r.longitude
  FROM repere_geo r
 WHERE s.latitude IS NULL
   AND r.quartier IS NULL
   AND normaliser_libelle(s.ville) = normaliser_libelle(r.ville);

------------------------------------------------------------------------------
-- Index
------------------------------------------------------------------------------
-- La recherche par distance commence par un cadre latitude/longitude, que cet
-- index sert directement ; le calcul exact ne s'applique qu'aux lignes
-- retenues. Partiel : un salon sans coordonnées n'a rien à y faire.
CREATE INDEX idx_salon_coordonnees
    ON salon (latitude, longitude)
    WHERE latitude IS NOT NULL;
