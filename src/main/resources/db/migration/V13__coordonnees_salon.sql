-- Coordonnées des salons : ce qu'il faut pour « les salons les plus proches de moi ».
--
-- Les colonnes latitude/longitude existaient depuis V1 mais aucune n'était
-- remplie et personne ne les lisait. Trier par distance demandait donc
-- d'abord de donner un point à chaque salon.
--
-- Le point vient de trois sources, par ordre de confiance décroissant :
--   1. les coordonnées saisies pour ce salon (relevées sur une carte) ;
--   2. le centre de son quartier ;
--   3. le centre de sa ville.
--
-- Un centre de quartier situe à quelques centaines de mètres, un centre de
-- ville à quelques kilomètres. C'est grossier pour afficher « à 800 m », mais
-- suffisant pour l'usage réel : classer les salons d'une ville du plus proche
-- au plus lointain. La précision annoncée dans l'interface suit la source.

------------------------------------------------------------------------------
-- Comparaison de libellés sans accent ni casse
------------------------------------------------------------------------------
-- « Guéliz », « Gueliz » et « GUÉLIZ » désignent le même quartier. L'extension
-- unaccent conviendrait mieux mais n'est pas garantie sur les hébergements
-- gérés ; translate() sur les accents du français et de la transcription
-- arabe couvre ce dont on a besoin, et reste IMMUTABLE — donc indexable.
CREATE OR REPLACE FUNCTION normaliser_libelle(valeur text)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE
AS $$
    -- lower() d'abord : il ramène déjà « GUÉLIZ » à « guéliz », le translate
    -- n'a donc que les minuscules accentuées à traiter. Apostrophes et tirets
    -- deviennent des espaces, puis les espaces répétés se réduisent à un seul,
    -- pour que « Centre-ville », « Centre ville » et « centre - ville » se
    -- rejoignent.
    SELECT btrim(regexp_replace(
        translate(
            lower(valeur),
            'àáâäãåéèêëíìîïóòôöõúùûüýÿñç''’-',
            'aaaaaaeeeeiiiiooooouuuuyync   '
        ),
        '\s+', ' ', 'g'
    ))
$$;

COMMENT ON FUNCTION normaliser_libelle(text) IS
    'Minuscules, sans accent, apostrophes et tirets ramenés à l''espace. '
    'Sert à rapprocher un quartier saisi à la main d''un repère connu.';

------------------------------------------------------------------------------
-- Repères géographiques
------------------------------------------------------------------------------
CREATE TABLE repere_geo (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ville      varchar(80) NOT NULL,
    -- NULL = le repère vaut pour la ville entière.
    quartier   varchar(80),
    latitude   double precision NOT NULL,
    longitude  double precision NOT NULL,
    CONSTRAINT chk_repere_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_repere_longitude CHECK (longitude BETWEEN -180 AND 180)
);

COMMENT ON TABLE repere_geo IS
    'Centres de villes et de quartiers marocains. Sert à situer un salon dont '
    'les coordonnées exactes n''ont pas été relevées. Table de référence : on '
    'y ajoute des lignes au fil des villes ouvertes, sans toucher au code.';

-- Un seul repère par couple ville/quartier, quelle que soit l'orthographe.
-- coalesce(...,'') parce qu'un index unique laisserait passer plusieurs NULL,
-- soit plusieurs centres pour la même ville.
CREATE UNIQUE INDEX uq_repere_geo_lieu
    ON repere_geo (normaliser_libelle(ville), normaliser_libelle(coalesce(quartier, '')));

