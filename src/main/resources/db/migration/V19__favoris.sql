-- Les salons qu'une cliente garde.
--
-- Une cliente de salon est fidèle : elle revient au même endroit, chez la
-- même personne. Jusqu'ici le site lui faisait refaire la recherche à chaque
-- fois — une raison de reprendre le téléphone. Un favori est un geste
-- explicite (le cœur), et il la suit d'un appareil à l'autre, ce qu'un
-- historique local ne fait pas.
--
-- (client, salon) est unique : on ne garde pas deux fois le même salon, et
-- la suppression d'un salon emporte ses favoris — il n'y a plus rien à y
-- retourner.
CREATE TABLE favori (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    salon_id  BIGINT      NOT NULL REFERENCES salon (id) ON DELETE CASCADE,
    cree_le   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_favori UNIQUE (client_id, salon_id)
);

